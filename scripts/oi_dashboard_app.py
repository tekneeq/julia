# ---------------------------------------------------------------------------
# Date helpers
# ---------------------------------------------------------------------------

def _next_business_day(d: date) -> date:
    while d.weekday() >= 5:
        d += timedelta(days=1)
    return d


def _add_business_days(d: date, n: int) -> date:
    """Return the date `n` business days after `d` (n=0 → d itself)."""
    while n > 0:
        d += timedelta(days=1)
        if d.weekday() < 5:
            n -= 1
    return d


def _compute_range(days_ahead: int) -> tuple[date, date, list[date]]:
    start = _next_business_day(date.today())
    end = _add_business_days(start, days_ahead - 1)
    exps: list[date] = []
    d = start
    while d <= end:
        if d.weekday() < 5:
            exps.append(d)
        d += timedelta(days=1)
    return start, end, exps


# ---------------------------------------------------------------------------
# PNG helpers
# ---------------------------------------------------------------------------

def _png_for(ticker: str, exp: date) -> Path:
    return PLOTS_DIR / f"oi-dashboard-{ticker}-{exp.isoformat()}.png"


def _age_str(path: Path) -> str:
    if not path.exists():
        return "not generated"
    mtime = datetime.fromtimestamp(path.stat().st_mtime)
    delta = datetime.now() - mtime
    secs = int(delta.total_seconds())
    if secs < 60:
        return f"{secs}s ago"
    if secs < 3600:
        return f"{secs // 60}m ago"
    if secs < 86400:
        return f"{secs // 3600}h {(secs % 3600) // 60}m ago"
    return f"{secs // 86400}d ago"


# ---------------------------------------------------------------------------
# Crossing-strike time series
# ---------------------------------------------------------------------------

def _parse_utc(iso_ts: str) -> datetime:
    return datetime.fromisoformat(iso_ts.replace("Z", "+00:00"))


def _crossing_history(ticker: str, expiration: date) -> list[dict]:
    """For each snapshot of (ticker, expiration), compute the cumulative
    dollar-OI crossing strike and pair it with the spot at that moment.

    Returns a list of dicts sorted oldest → newest so plotting is a
    straight time series. Skips snapshots that don't have enough data to
    compute a crossing (e.g. one-sided chains).
    """
    rows = gex_store.recent_snapshots(
        ticker=ticker, expiration_date=expiration.isoformat(), limit=500
    )
    if not rows:
        return []

    history: list[dict] = []
    for r in rows:
        df = _load_oi_snapshot_df(r)
        if df is None or df.empty:
            continue
        spot = float(r["spot_price"])
        series = _prepare_oi_series(df, spot=spot, metric="dollars", range_pct=0)
        if series is None:
            continue
        call_cum = np.cumsum(series["call_vals"])
        put_arr = np.array(series["put_vals_positive"])
        put_cum = np.cumsum(put_arr[::-1])[::-1]
        cx, cy = _find_curve_crossing(series["strikes"], call_cum, put_cum)
        if cx is None:
            continue
        history.append({
            "captured_at_utc": _parse_utc(r["captured_at"]),
            "captured_at_local": _parse_utc(r["captured_at"]).astimezone(),
            "crossing_strike": float(cx),
            "crossing_dollars": float(cy) if cy is not None else None,
            "spot_price": spot,
        })

    history.sort(key=lambda h: h["captured_at_utc"])
    return history


def _render_crossing_chart(ticker: str, expiration: date, history: list[dict]) -> None:
    if not history:
        st.info(
            f"No snapshots yet for {ticker} {expiration.isoformat()}. "
            "Run **oi-dashboard** at least once to seed the history."
        )
        return

    ts = [h["captured_at_local"] for h in history]
    cross = [h["crossing_strike"] for h in history]
    spot = [h["spot_price"] for h in history]
    single = len(history) == 1

    fig = go.Figure()
    fig.add_trace(go.Scatter(
        x=ts, y=cross,
        mode="markers" if single else "lines+markers",
        name="Crossing strike",
        line=dict(color="#1f77b4", width=2.5),
        marker=dict(size=12 if single else 8, color="#1f77b4"),
        hovertemplate=(
            "<b>%{x|%Y-%m-%d %H:%M}</b><br>"
            "Crossing: <b>$%{y:.2f}</b><extra></extra>"
        ),
    ))
    fig.add_trace(go.Scatter(
        x=ts, y=spot,
        mode="markers" if single else "lines+markers",
        name="Spot",
        line=dict(color="#111", dash="dash", width=1.5),
        marker=dict(size=10 if single else 6, symbol="circle-open", color="#111"),
        hovertemplate=(
            "<b>%{x|%Y-%m-%d %H:%M}</b><br>"
            "Spot: <b>$%{y:.2f}</b><extra></extra>"
        ),
    ))

    first, last = history[0], history[-1]
    delta_cross = last["crossing_strike"] - first["crossing_strike"]
    delta_spot = last["spot_price"] - first["spot_price"]
    span_min = (last["captured_at_utc"] - first["captured_at_utc"]).total_seconds() / 60
    if single:
        span_str = "single snapshot"
    else:
        span_str = (
            f"{span_min / 60 / 24:.1f} days" if span_min >= 60 * 24
            else f"{span_min / 60:.1f} hours" if span_min >= 60
            else f"{span_min:.0f} min"
        )

    # With a single point, Plotly's autorange picks a tiny window and the
    # dot floats in the middle of nowhere. Pad the y-axis so the dot + spot
    # sit at a sensible scale, and widen the x-axis so it doesn't look like
    # the chart is broken.
    layout_kwargs: dict = dict(
        title=(
            f"{ticker} {expiration.isoformat()} — crossing strike over time  "
            f"·  {len(history)} snapshot{'s' if len(history) != 1 else ''} "
            f"over {span_str}"
        ),
        xaxis_title="Snapshot time (local)",
        yaxis_title="Strike ($)",
        height=380,
        hovermode="x unified",
        legend=dict(orientation="h", y=1.08, x=0),
        margin=dict(t=60, l=60, r=20, b=40),
    )
    if single:
        t0 = ts[0]
        layout_kwargs["xaxis"] = dict(
            range=[t0 - timedelta(hours=6), t0 + timedelta(hours=6)],
        )
        lo = min(cross[0], spot[0])
        hi = max(cross[0], spot[0])
        pad = max((hi - lo) * 2.0, 2.0)
        layout_kwargs["yaxis"] = dict(range=[lo - pad, hi + pad])

    fig.update_layout(**layout_kwargs)
    fig.update_yaxes(tickformat="$.2f")

    st.plotly_chart(fig, use_container_width=True)

    col_a, col_b, col_c = st.columns(3)
    with col_a:
        st.metric(
            "Latest crossing",
            f"${last['crossing_strike']:.2f}",
            None if single else f"{delta_cross:+.2f} vs first",
        )
    with col_b:
        st.metric(
            "Latest spot",
            f"${last['spot_price']:.2f}",
            None if single else f"{delta_spot:+.2f} vs first",
        )
    with col_c:
        gap = last["crossing_strike"] - last["spot_price"]
        st.metric(
            "Crossing − spot (now)",
            f"{gap:+.2f}",
            help=(
                "Positive = the pin/max-pain magnet is above spot; "
                "negative = below."
            ),
        )
    if single:
        st.caption(
            "Only one snapshot so far — run `oi-dashboard` again "
            "(or the batch) to start seeing movement over time."
        )


# ---------------------------------------------------------------------------
# Background batch runner
# ---------------------------------------------------------------------------

def _kickoff_batch(
    tickers: list[str],
    start: date,
    end: date,
    refresh_cache: bool,
) -> None:
    """Spawn oi_batch.py as a background subprocess (non-blocking)."""
    cmd = [
        str(BATCH_SCRIPT),
        "--from", start.isoformat(),
        "--to", end.isoformat(),
        "--tickers", ",".join(tickers),
    ]
    if not refresh_cache:
        cmd.append("--no-refresh-cache")

    env = os.environ.copy()
    env.setdefault("UV_NATIVE_TLS", "true")

    log_path = REPO_ROOT / "logs" / "oi-batch" / "_streamlit_last_run.log"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_file = open(log_path, "w")

    proc = subprocess.Popen(
        cmd, cwd=REPO_ROOT, env=env, stdout=log_file, stderr=subprocess.STDOUT,
    )
    st.session_state["_batch_proc"] = proc
    st.session_state["_batch_log_path"] = str(log_path)
    st.session_state["_batch_started_at"] = time.time()


def _poll_batch() -> str:
    """Return one of: 'idle', 'running', 'done', 'failed'."""
    proc = st.session_state.get("_batch_proc")
    if proc is None:
        return "idle"
    rc = proc.poll()
    if rc is None:
        return "running"
    st.session_state["_batch_rc"] = rc
    st.session_state["_batch_finished_at"] = time.time()
    st.session_state["_batch_proc"] = None
    return "done" if rc == 0 else "failed"


