@st.cache_data(ttl=300, show_spinner=False)
def _store_prior_5min_bars(ticker: str, today_iso: str) -> list[dict]:
    """Rebuild prior-session 5-minute OHLC from the local minute path."""
    today = date.fromisoformat(today_iso)
    bars: list[dict] = []
    for s in daily_moves_store.list_sessions(ticker):
        try:
            d = date.fromisoformat(s["session_date"])
        except ValueError:
            continue
        if d >= today:
            continue
        path = daily_moves_store.get_session_path(ticker, d)
        if not path:
            continue
        series = [
            {
                "ts": _minute_to_dt(d, p["minutes_from_open"]),
                "price": p["spot"],
            }
            for p in path
        ]
        bars.extend(_five_min_bars(series, d))
    bars.sort(key=lambda b: b["ts"])
    return bars


def _history_5min_bars(
    ticker: str, today: date, series: list[dict],
) -> list[dict]:
    """Prior-session 5-minute OHLC plus today's live-aggregated bars.

    Robinhood official bars win over reconstructed store bars; today's
    live ticks win over both so the developing candle stays real-time.
    """
    by_ts: dict[datetime, dict] = {}
    for b in _store_prior_5min_bars(ticker, today.isoformat()):
        if _is_regular_bar_ts(b["ts"]):
            by_ts[b["ts"]] = b
    # Official RH bars overwrite reconstructed store OHLC; include
    # today so a late poller start still has the morning.
    for b in _fetch_rh_ohlc_merged(
        ticker, "5minute", ("month", "week", "day"),
    ):
        if not _is_regular_bar_ts(b["ts"]):
            continue
        by_ts[b["ts"]] = b
    for b in _five_min_bars(series, today):
        prev = by_ts.get(b["ts"])
        # Live ticks replace OHLC but keep Robinhood volume so the
        # developing candle still has a participation read.
        if prev is not None and prev.get("v") is not None:
            b = {**b, "v": prev["v"]}
        by_ts[b["ts"]] = b
    return [by_ts[k] for k in sorted(by_ts)]


@st.cache_data(ttl=300, show_spinner=False)
def _prior_5min_closes(ticker: str, today_iso: str) -> list[float]:
    """Closes of regular-session 5-minute bars BEFORE today, oldest
    first — warm-up history so SMA/EMA are correct from the open
    (a 27-bar EMA otherwise needs 2h15m of today before it exists).

    Regular hours are 13:30–20:00 UTC, so the UTC date prefix of
    ``begins_at`` matches the ET session date.
    """
    out: list[tuple[str, float]] = []
    for c in _fetch_rh_5min(ticker, "week"):
        begins = c.get("begins_at") or ""
        close = c.get("close_price")
        if not begins or begins[:10] >= today_iso or close is None:
            continue
        try:
            out.append((begins, float(close)))
        except (TypeError, ValueError):
            continue
    out.sort()
    return [c for _, c in out]


def _ma_over_bars(
    prior_closes: list[float], bar_closes: list[float],
    *, sma_bars: int = _SMA_BARS, ema_bars: int = _EMA_BARS,
) -> tuple[list[float | None], list[float | None]]:
    """(SMA, EMA) aligned to ``bar_closes``, warmed up with
    ``prior_closes``. Periods default to 9 / 27 of whatever
    timeframe the closes belong to. ``None`` where the window
    isn't filled yet. EMA seeds with the SMA of its first
    period (charting convention).
    """
    closes = prior_closes + bar_closes
    n = len(closes)
    n_prior = len(prior_closes)

    sma_full: list[float | None] = [None] * n
    if sma_bars > 0 and n >= sma_bars:
        window = sum(closes[:sma_bars])
        sma_full[sma_bars - 1] = window / sma_bars
        for i in range(sma_bars, n):
            window += closes[i] - closes[i - sma_bars]
            sma_full[i] = window / sma_bars

    ema_full: list[float | None] = [None] * n
    if ema_bars > 0 and n >= ema_bars:
        ema = sum(closes[:ema_bars]) / ema_bars
        ema_full[ema_bars - 1] = ema
        alpha = 2.0 / (ema_bars + 1)
        for i in range(ema_bars, n):
            ema = alpha * closes[i] + (1.0 - alpha) * ema
            ema_full[i] = ema

    return sma_full[n_prior:], ema_full[n_prior:]


def _render_today_price_chart(ticker: str, today: date, status: dict) -> None:
    """TradingView-style live session chart: $ on the right, % vs prev
    close on the left, crosshair spikes, prev-close baseline with
    green/red tint, H/L markers labeled with P(day extreme), SMA 9 /
    EMA 27 curves on 5-minute bars, and a dotted last-price line with
    a right-axis box (price + time left on the 5-min bar). Toggles
    between 5-min candles (TradingView-like) and the tick line.
    Default window is today's session; prior 5-minute bars are on the
    same traces so zooming/panning the time axis reveals them. No
    twins here — they get their own panels below.
    """
    series = _today_price_series(ticker, today)
    ref = status.get("today_ref")
    ref_src = status.get("today_ref_source", "?")
    if not series:
        st.info(
            f"No price data yet for {ticker} today. Start the price "
            "poller (`./restart-price-poller.sh`) for tick-level data, "
            "or wait for the next scheduler fire / market-bar sync."
        )
        return

    xs = [e["ts"] for e in series]
    ys = [e["price"] for e in series]
    n_ticks = sum(1 for e in series if e["source"] == "tick")
    n_fallback = len(series) - n_ticks
    last_ts, last_price = xs[-1], ys[-1]
