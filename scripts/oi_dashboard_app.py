_SESSION_MINUTES = (
    daily_moves_store.MARKET_CLOSE.hour * 60
    + daily_moves_store.MARKET_CLOSE.minute
    - (daily_moves_store.MARKET_OPEN.hour * 60
       + daily_moves_store.MARKET_OPEN.minute)
)  # 390 for a regular session


def _prior_close_spot(ticker: str, session: date) -> float | None:
    """Last known spot strictly before ``session`` — prior-session close."""
    rows = gex_store.recent_snapshots(ticker=ticker, limit=10000)
    best: tuple[datetime, float] | None = None
    for r in rows:
        local_dt = _parse_utc(r["captured_at"]).astimezone()
        if local_dt.date() >= session:
            continue
        if best is None or local_dt > best[0]:
            best = (local_dt, float(r["spot_price"]))
    return best[1] if best else None


def _ingest_snapshot_paths(ticker: str, lookback_calendar_days: int = 60) -> None:
    """Upsert daily paths from gex_snapshots spot stamps."""
    cutoff = date.today() - timedelta(days=lookback_calendar_days)
    rows = gex_store.recent_snapshots(ticker=ticker, limit=10000)
    # local_date → {minutes_from_open: (captured_at, spot)}  (latest wins)
    by_day: dict[date, dict[int, tuple[datetime, float]]] = {}
    # Also track last spot per day for prior-close lookup.
    last_spot_by_day: dict[date, tuple[datetime, float]] = {}
    for r in rows:
        local_dt = _parse_utc(r["captured_at"]).astimezone()
        d = local_dt.date()
        spot = float(r["spot_price"])
        prev_last = last_spot_by_day.get(d)
        if prev_last is None or local_dt > prev_last[0]:
            last_spot_by_day[d] = (local_dt, spot)
        if d < cutoff or d.weekday() >= 5:
            continue
        m = daily_moves_store.minutes_from_open(local_dt)
        # Keep points inside the regular session (± a few min of open/close).
        if m < -5 or m > _SESSION_MINUTES + 15:
            continue
        m = max(0, min(m, _SESSION_MINUTES))
        day_map = by_day.setdefault(d, {})
        prev = day_map.get(m)
        if prev is None or local_dt > prev[0]:
            day_map[m] = (local_dt, spot)

    prior_days = sorted(last_spot_by_day)
    for d in sorted(by_day):
        # Prior close = last spot of the most recent earlier session day.
        ref = None
        for pd in reversed(prior_days):
            if pd < d:
                ref = last_spot_by_day[pd][1]
                break
        if ref is None or ref <= 0:
            continue
        daily_moves_store.upsert_session(
            ticker=ticker, session_date=d, ref_spot=ref,
        )
        points = [
            (m, spot, (spot - ref) / ref * 100.0, "snapshot")
            for m, (_ts, spot) in sorted(by_day[d].items())
        ]
        daily_moves_store.upsert_points(
            ticker=ticker, session_date=d, points=points,
        )


def _ohlc_bar_polyline(
    m_start: int, o: float, h: float, low: float, c: float,
) -> list[tuple[int, float]]:
    """Turn one 5-minute OHLC bar into a short polyline that keeps the wick.

    Without this, a bar that opens high and closes near the low collapses
    to a single close print — the sharp drop the user actually saw never
    appears on the chart. Order follows the usual convention:
    up-bar → open, low, high, close; down-bar → open, high, low, close.
    Timestamps are spaced inside the 5-minute window.
    """
    m0 = max(0, min(m_start, _SESSION_MINUTES))
    m1 = max(0, min(m_start + 1, _SESSION_MINUTES))
    m3 = max(0, min(m_start + 3, _SESSION_MINUTES))
    m5 = max(0, min(m_start + 5, _SESSION_MINUTES))
    # Flat / doji — just open → close.
    if abs(h - low) < 1e-9:
        return [(m0, o), (m5, c)] if m5 != m0 else [(m0, c)]
    if c >= o:
        return [(m0, o), (m1, low), (m3, h), (m5, c)]
    return [(m0, o), (m1, h), (m3, low), (m5, c)]


def _fetch_rh_5min(ticker: str, span: str) -> list[dict]:
    """Raw 5-minute bars or [] on any failure.

    Robinhood occasionally returns ``None`` slots in the list — drop
    those so callers can safely ``.get(...)`` on each candle.
    """
    if not _rh_market_data_ready():
        return []
    import robin_stocks.robinhood as rh
    try:
        bars = rh.stocks.get_stock_historicals(
            ticker, interval="5minute", span=span, bounds="regular",
        ) or []
    except Exception:
        return []
    return [c for c in bars if isinstance(c, dict)]


@st.cache_data(ttl=300, show_spinner=False)
def _fetch_rh_daily_closes(ticker: str) -> dict[str, float]:
    """date-iso → regular-session close from Robinhood daily bars."""
    if not _rh_market_data_ready():
        return {}
    import robin_stocks.robinhood as rh
    try:
        bars = rh.stocks.get_stock_historicals(
            ticker, interval="day", span="month", bounds="regular",
        ) or []
    except Exception:
        return {}
    out: dict[str, float] = {}
    for bar in bars:
        if not isinstance(bar, dict):
            continue
        d_iso = (bar.get("begins_at") or "")[:10]
        close = bar.get("close_price")
        if not d_iso or close is None:
            continue
        try:
            out[d_iso] = float(close)
        except (TypeError, ValueError):
            continue
    return out


def _official_prior_close(ticker: str, session: date) -> float | None:
    """Most recent official daily close strictly before ``session``."""
    closes = _fetch_rh_daily_closes(ticker)
    prior: tuple[date, float] | None = None
    for d_iso, close in closes.items():
        try:
            d = date.fromisoformat(d_iso)
        except ValueError:
            continue
        if d < session and (prior is None or d > prior[0]):
            prior = (d, close)
    return prior[1] if prior else None


def _resolve_ref_spot(ticker: str, session: date) -> tuple[float | None, str]:
    """Pick the % baseline. Official prior close always wins.

    Snapshot-based refs are last-batch stamps, which can sit well above
    or below the real 4pm close — that flattens an opening gap on the
    twin chart (e.g. TradingView prev close 741.69 vs a 743.45 snapshot).
    """
    official = _official_prior_close(ticker, session)
    if official is not None and official > 0:
        return official, "official"
    snap = _prior_close_spot(ticker, session)
    if snap is not None and snap > 0:
        return snap, "snapshot"
    return None, "none"


def _ingest_market_paths(ticker: str) -> int:
    """Densify today + recent days with Robinhood 5-minute OHLC bars.

    Fetches ``span='day'`` (freshest today) and ``span='week'`` (recent
    history). Each bar is expanded to an open→wick→close polyline so a
    high open that dumps inside the first hour actually shows up as a
    sharp drop, not a single close print. Returns the number of market
    points upserted (0 when auth/network fails).
    """
    # Day last so today's bars win over the week payload on conflicts.
    candles_by_key: dict[str, dict] = {}
    for span in ("week", "day"):
        for c in _fetch_rh_5min(ticker, span):
            if not isinstance(c, dict):
                continue
            begins = c.get("begins_at") or ""
            if begins:
                candles_by_key[begins] = c
    if not candles_by_key:
        return 0

    # day → list of (m_start, open, high, low, close)
    by_day: dict[date, list[tuple[int, float, float, float, float]]] = {}
    for begins, c in candles_by_key.items():
        try:
            local_dt = _parse_utc(begins).astimezone()
            o = float(c["open_price"])
            h = float(c["high_price"])
            low = float(c["low_price"])
            cl = float(c["close_price"])
        except (KeyError, TypeError, ValueError):
            continue
        d = local_dt.date()
        if d.weekday() >= 5:
            continue
        m = daily_moves_store.minutes_from_open(local_dt)
        if m < -1 or m > _SESSION_MINUTES:
            continue
        m = max(0, m)
        by_day.setdefault(d, []).append((m, o, h, low, cl))

    upserted = 0
    for d, bars in by_day.items():
        bars.sort(key=lambda b: b[0])
        ref, _src = _resolve_ref_spot(ticker, d)
        if ref is None:
            continue
        # rebase_session updates ref AND rewrites pct on any points
        # already stored against a stale snapshot-based ref.
        daily_moves_store.rebase_session(
            ticker=ticker, session_date=d, ref_spot=ref,
        )
        # Expand bars → polyline, then collapse to one spot per minute
        # (last write wins, so close of a bar beats the next bar's open
        # when they share a boundary minute).
        by_min: dict[int, float] = {}
        for m_start, o, h, low, cl in bars:
            for m, spot in _ohlc_bar_polyline(m_start, o, h, low, cl):
                by_min[m] = spot
        # Guarantee the true session open is at minute 0 (first bar open).
        first = bars[0]
        by_min[0] = first[1]  # open of earliest bar
        points = [
            (m, spot, (spot - ref) / ref * 100.0, "market")
            for m, spot in sorted(by_min.items())
        ]
        daily_moves_store.upsert_points(
            ticker=ticker, session_date=d, points=points,
        )
        upserted += len(points)
    return upserted


def _ingest_tick_paths(ticker: str, today: date) -> int:
    """Distill today's poller ticks into per-minute points (source='tick').

    The raw sub-minute prints stay in ``spot_ticks`` for the live chart;
    this collapses them (last print per minute wins) so the twin matcher
    sees today's path at real-tick fidelity instead of 5-minute bars.
    Returns the number of minute points upserted.
    """
    ticks = daily_moves_store.get_ticks(ticker, today)
    if not ticks:
        return 0
    ref, _src = _resolve_ref_spot(ticker, today)
    if ref is None or ref <= 0:
        # Robinhood unreachable and no snapshots yet — reuse the ref a
        # previous sync stored for today rather than dropping the ticks.
        ref = next(
            (
                float(s["ref_spot"])
                for s in daily_moves_store.list_sessions(ticker)
                if s["session_date"] == today.isoformat()
            ),
            None,
        )
    if ref is None or ref <= 0:
        return 0
    daily_moves_store.upsert_session(
        ticker=ticker, session_date=today, ref_spot=ref,
    )
    by_min: dict[int, float] = {}
    for t in ticks:
        m = daily_moves_store.minutes_from_open(t["ts"])
        if m < -2 or m > _SESSION_MINUTES + 2:
            continue
        by_min[max(0, min(m, _SESSION_MINUTES))] = t["price"]
    points = [
        (m, spot, (spot - ref) / ref * 100.0, "tick")
        for m, spot in sorted(by_min.items())
    ]
    daily_moves_store.upsert_points(
        ticker=ticker, session_date=today, points=points,
    )
    return len(points)


def _rebase_all_sessions_to_official_close(ticker: str) -> int:
    """Correct every stored session whose ref isn't the official prior close.

    Snapshot ingest runs first and can lock in a mid-afternoon stamp as
    ``ref_spot``. Even after densifying with market bars, % paths stay
    wrong until we rebase. Returns how many sessions were corrected.
    """
    corrected = 0
    for s in daily_moves_store.list_sessions(ticker):
        d = date.fromisoformat(s["session_date"])
        official = _official_prior_close(ticker, d)
        if official is None or official <= 0:
            continue
        old = float(s["ref_spot"])
        if abs(old - official) / official < 1e-5:
            continue
        daily_moves_store.rebase_session(
            ticker=ticker, session_date=d, ref_spot=official,
        )
        corrected += 1
    return corrected


@st.cache_data(ttl=30, show_spinner=False)
def _sync_daily_move_library(ticker: str, today_iso: str) -> dict:
    """Refresh the 30-session library and return a small status dict."""
    today = date.fromisoformat(today_iso)
    _ingest_snapshot_paths(ticker)
    market_pts = _ingest_market_paths(ticker)
    rebased = _rebase_all_sessions_to_official_close(ticker)
    # Ticks fold last so their per-minute points are computed against
    # the (possibly just-rebased) official prior close.
    tick_pts = _ingest_tick_paths(ticker, today)
    deleted = daily_moves_store.prune(
        ticker, keep=daily_moves_store.KEEP_SESSIONS, today=today,
    )
    daily_moves_store.prune_ticks(ticker)
    sessions = daily_moves_store.list_sessions(ticker)
    today_path = daily_moves_store.get_session_path(ticker, today)
    sources = {p["source"] for p in today_path}
    today_ref = next(
        (float(s["ref_spot"]) for s in sessions
         if s["session_date"] == today_iso),
        None,
    )
    _, ref_src = _resolve_ref_spot(ticker, today)
    if ref_src == "none" and today_ref is not None:
        # Robinhood/snapshots unreachable right now, but a prior sync
        # already pinned today's ref — report that instead of "none".
        ref_src = "stored"
    return {
        "n_sessions": len(sessions),
        "pruned": deleted,
        "rebased": rebased,
        "dates": [r["session_date"] for r in sessions],
        "market_points": market_pts,
        "tick_minute_points": tick_pts,
        "today_points": len(today_path),
        "today_sources": sorted(sources),
        "today_first_m": today_path[0]["minutes_from_open"] if today_path else None,
        "today_last_m": today_path[-1]["minutes_from_open"] if today_path else None,
        "today_ref": today_ref,
        "today_ref_source": ref_src,
        "today_open_pct": today_path[0]["pct"] if today_path else None,
        "today_low_pct": (
            min(p["pct"] for p in today_path) if today_path else None
        ),
    }


def _interpolate_pct(path: list[dict], minute: int) -> float | None:
    """Linear interp of pct at ``minute``; None if outside the path span."""
    if not path:
        return None
    xs = [p["minutes_from_open"] for p in path]
    ys = [p["pct"] for p in path]
    if minute < xs[0] or minute > xs[-1]:
        return None
    if minute in xs:
        return ys[xs.index(minute)]
    # Find bracketing points
    for i in range(1, len(xs)):
        if xs[i] >= minute:
            x0, x1 = xs[i - 1], xs[i]
            y0, y1 = ys[i - 1], ys[i]
            if x1 == x0:
                return y0
            t = (minute - x0) / (x1 - x0)
            return y0 + t * (y1 - y0)
    return None


def _path_rmse(today_path: list[dict], hist_path: list[dict]) -> float | None:
    """Recency-weighted RMSE of % move on today's sample minutes.

    Later points weigh more (linear in minutes from open, floored at 1),
    so a mid-day reversal can switch the twin away from whatever matched
    the open. Needs ≥2 overlapping points.
    """
    if len(today_path) < 2:
        return None
    weighted: list[tuple[float, float]] = []  # (weight, error)
    for p in today_path:
        h = _interpolate_pct(hist_path, p["minutes_from_open"])
        if h is None:
            continue
        w = max(float(p["minutes_from_open"]), 1.0)
        weighted.append((w, p["pct"] - h))
    if len(weighted) < 2:
        return None
    wsum = sum(w for w, _e in weighted)
    return math.sqrt(sum(w * e * e for w, e in weighted) / wsum)


def _today_implied_1sigma_pct(ticker: str, today: date) -> float | None:
    """Prior-session 1σ implied move for ``today``, in percent of spot."""
    hist = _implied_vs_actual_history(ticker, 1, today.isoformat())
    if not hist:
        return None
    row = hist[-1]
    if row.get("day") != today:
        return None
    implied = row.get("implied") or None
    if not implied:
        return None
    conf1 = IMPLIED_MOVE_LEVELS[0][0]
    val = implied.get(conf1)
    return float(val) if val is not None else None


def _sigma_extreme_hold_prob(
    *,
    last_pct: float,
    extreme_pct: float,
    sigma_1pct: float | None,
    now_m: int,
    side: str,
) -> float | None:
    """Analytic P(extreme holds) from remaining-session σ (driftless BM).

    ``side`` is ``"high"`` or ``"low"``. Uses the reflection-principle
    approx ``P(new extreme) ≈ 2·(1−Φ(a/σ_rem))`` clipped to [0, 1].
    """
    if sigma_1pct is None or sigma_1pct <= 0:
        return None
    rem = max(_SESSION_MINUTES - now_m, 0)
    if rem <= 0:
        return 1.0
    sigma_rem = sigma_1pct * math.sqrt(rem / _SESSION_MINUTES)
    if sigma_rem < 1e-9:
        return 1.0
    if side == "high":
        a = extreme_pct - last_pct  # how far above last a new high needs
    else:
        a = last_pct - extreme_pct  # how far below last a new low needs
    # Already away from the extreme → holding is likelier. At the print
    # (a≈0) continuous BM would say P(new extreme)≈1; floor a so a
    # fresh tick doesn't force ~0% hold from the σ prior alone.
    a = max(a, 0.05 * sigma_1pct)
    p_new = min(1.0, max(0.0, 2.0 * (1.0 - float(norm.cdf(a / sigma_rem)))))
    return 1.0 - p_new


def _extreme_survival_probs(
    ticker: str,
    today: date,
    today_path: list[dict],
    *,
    sigma_1pct: float | None = None,
) -> dict | None:
    """P(current high/low so far are the full-day extremes).

    Primary signal: among completed sessions that reached this time of
    day, what fraction never made a new high/low afterward. Days whose
    path shape is closer to today (lower RMSE) get more weight.

    Optional blend with a remaining-session 1σ Brownian prior when the
    prior-session implied move is available.

    Returns None when the library is too thin / too early to be useful.
    """
    if not today_path or len(today_path) < 2:
        return None
    now_m = int(today_path[-1]["minutes_from_open"])
    last_pct = float(today_path[-1]["pct"])
    today_hi = max(p["pct"] for p in today_path)
    today_lo = min(p["pct"] for p in today_path)
    at_high = abs(last_pct - today_hi) < 1e-9
    at_low = abs(last_pct - today_lo) < 1e-9

    if now_m >= _SESSION_MINUTES:
        return {
            "p_high": 1.0, "p_low": 1.0, "n": 0, "now_m": now_m,
            "at_high": at_high, "at_low": at_low,
            "basis": "session closed",
        }

    # Too early — historical prefixes are noisy and almost never "done".
    if now_m < 15:
        return None

    eps = 1e-6
    w_high = w_low = 0.0
    held_high = held_low = 0.0
    n = 0
    for s in daily_moves_store.list_sessions(ticker):
        d = date.fromisoformat(s["session_date"])
        if d >= today:
            continue
        hist = daily_moves_store.get_session_path(ticker, d)
        if not hist or hist[-1]["minutes_from_open"] < now_m:
            continue
        prefix = [p for p in hist if p["minutes_from_open"] <= now_m]
        if len(prefix) < 2:
            continue
        prefix_hi = max(p["pct"] for p in prefix)
        prefix_lo = min(p["pct"] for p in prefix)
        day_hi = max(p["pct"] for p in hist)
        day_lo = min(p["pct"] for p in hist)
        rmse = _path_rmse(today_path, hist)
        w = 1.0 / (rmse + 0.05) if rmse is not None else 1.0
        n += 1
        w_high += w
        w_low += w
        if day_hi <= prefix_hi + eps:
            held_high += w
        if day_lo >= prefix_lo - eps:
            held_low += w

    emp_high = (held_high / w_high) if w_high > 0 else None
    emp_low = (held_low / w_low) if w_low > 0 else None

    sig_high = _sigma_extreme_hold_prob(
        last_pct=last_pct, extreme_pct=today_hi,
        sigma_1pct=sigma_1pct, now_m=now_m, side="high",
    )
    sig_low = _sigma_extreme_hold_prob(
        last_pct=last_pct, extreme_pct=today_lo,
        sigma_1pct=sigma_1pct, now_m=now_m, side="low",
    )

    def _blend(emp: float | None, sig: float | None) -> float | None:
        if emp is not None and sig is not None:
            return 0.7 * emp + 0.3 * sig
        return emp if emp is not None else sig

    p_high = _blend(emp_high, sig_high)
    p_low = _blend(emp_low, sig_low)
    if p_high is None or p_low is None:
        return None
    if n < 5 and sig_high is None:
        return None

    if emp_high is not None and sig_high is not None:
        basis = (
            f"path-weighted history (n={n}) blended with remaining-session σ"
        )
    elif emp_high is not None:
        basis = f"path-weighted history (n={n})"
    else:
        basis = "remaining-session σ prior"

    return {
        "p_high": float(p_high),
        "p_low": float(p_low),
        "n": n,
        "now_m": now_m,
        "at_high": at_high,
        "at_low": at_low,
        "basis": basis,
    }


def _find_path_twins(
    ticker: str, query_day: date, *, top_n: int = 3,
) -> dict:
    """Closest completed sessions to ``query_day``'s path by RMSE.

    Each candidate also carries the *next* business day's path (when we
    have it) — used by the "yesterday → next day" twin panel to show
    what followed the last time a similar session printed.
    """
    query_path = daily_moves_store.get_session_path(ticker, query_day)
    sessions = daily_moves_store.list_sessions(ticker)
    sessions_by_day = {
        date.fromisoformat(s["session_date"]): s for s in sessions
    }
    candidates: list[dict] = []
    for s in sessions:
        d = date.fromisoformat(s["session_date"])
        if d >= query_day:
            continue
        hist = daily_moves_store.get_session_path(ticker, d)
        rmse = _path_rmse(query_path, hist)
        if rmse is None:
            continue
        nxt = _add_business_days(d, 1)
        next_path = daily_moves_store.get_session_path(ticker, nxt)
        candidates.append({
            "day": d,
            "ref_spot": float(s["ref_spot"]),
            "path": hist,
            "rmse": rmse,
            "final_pct": hist[-1]["pct"] if hist else None,
            "next_day": nxt if next_path else None,
            "next_path": next_path or None,
            "next_ref_spot": (
                float(sessions_by_day[nxt]["ref_spot"])
                if nxt in sessions_by_day else None
            ),
            "next_final_pct": (
                next_path[-1]["pct"] if next_path else None
            ),
        })
    candidates.sort(key=lambda c: c["rmse"])
    query_ref = next(
        (float(s["ref_spot"]) for s in sessions
         if s["session_date"] == query_day.isoformat()),
        None,
    )
    return {
        "query_day": query_day,
        "query_path": query_path,
        "query_ref": query_ref,
        "twins": candidates[:top_n],
        "library_size": sum(
            1 for s in sessions
            if s["session_date"] != query_day.isoformat()
        ),
    }


def _find_daily_twins(
    ticker: str, today: date, *, top_n: int = 3,
) -> dict:
    """Today's path + the closest completed sessions by RMSE so far."""
    result = _find_path_twins(ticker, today, top_n=top_n)
    # Keep the legacy keys the today-twin renderer still reads.
    return {
        "today": result["query_day"],
        "today_path": result["query_path"],
        "today_ref": result["query_ref"],
        "twins": result["twins"],
        "library_size": result["library_size"],
    }


