@st.cache_resource(ttl=900, show_spinner=False)
def _rh_market_data_ready() -> bool:
    """Best-effort Robinhood auth so the candles can use official OHLC.

    Reuses the CLI's cached token when one exists (~/.tokens is mounted
    into the container), else tries RH_USERNAME/RH_PASSWORD from the
    environment. Cached per process with a 15-min ttl so a transient
    failure retries instead of disabling market data until restart.
    """
    try:
        from julia.main import is_logged_in, login_robinhood
        if is_logged_in():
            return True
        username = os.getenv("RH_USERNAME")
        password = os.getenv("RH_PASSWORD")
        if username and password:
            login_robinhood(username, password)
            return is_logged_in()
    except Exception:
        pass
    return False


@st.cache_data(ttl=120, show_spinner=False)
def _market_daily_ohlc(ticker: str, today_iso: str) -> dict[str, dict[str, float]]:
    """date-iso → {open, high, low, close} from Robinhood; {} when
    unavailable (not logged in, network down).

    The snapshot-derived candles are sampled at the batch cadence: if the
    scheduler starts late, the first snapshot masquerades as the "open"
    and the true high/low between fires are invisible. Official bars fix
    that. Past days come from daily bars; today from 5-minute candles,
    because the running day-bar lags during the session.
    """
    if not _rh_market_data_ready():
        return {}
    import robin_stocks.robinhood as rh

    out: dict[str, dict[str, float]] = {}
    try:
        bars = rh.stocks.get_stock_historicals(
            ticker, interval="day", span="month", bounds="regular"
        ) or []
        for bar in bars:
            if not isinstance(bar, dict):
                continue
            d = (bar.get("begins_at") or "")[:10]
            try:
                out[d] = {
                    "open": float(bar["open_price"]),
                    "high": float(bar["high_price"]),
                    "low": float(bar["low_price"]),
                    "close": float(bar["close_price"]),
                }
            except (KeyError, TypeError, ValueError):
                continue
    except Exception:
        pass
    try:
        # Regular hours are 13:30–20:00 UTC, so the UTC date prefix of
        # `begins_at` matches the ET session date.
        candles = [
            c for c in (rh.stocks.get_stock_historicals(
                ticker, interval="5minute", span="day", bounds="regular"
            ) or [])
            if isinstance(c, dict)
            and (c.get("begins_at") or "").startswith(today_iso)
        ]
        opens = [c for c in candles if c.get("open_price")]
        highs = [float(c["high_price"]) for c in candles if c.get("high_price")]
        lows = [float(c["low_price"]) for c in candles if c.get("low_price")]
        closes = [c for c in candles if c.get("close_price")]
        if opens and highs and lows and closes:
            out[today_iso] = {
                "open": float(opens[0]["open_price"]),
                "high": max(highs),
                "low": min(lows),
                "close": float(closes[-1]["close_price"]),
            }
    except Exception:
        pass
    return out


@st.cache_data(ttl=60, show_spinner=False)
def _implied_vs_actual_history(
    ticker: str, num_days: int, end_iso: str,
) -> list[dict]:
    """For each of the ``num_days`` business days ending at ``end_iso``
    (inclusive — normally today), pair the implied move that was priced
    in *before* the session with the move that actually happened.

    Key convention (per the section's purpose): the implied numbers for
    day D come from the **latest snapshot captured before D** — normally
    the last batch fire of the prior session — NOT from anything captured
    during D itself. That holds for today too: today's bands are frozen
    at yesterday's close while today's actual/high/low update live as
    new snapshots land. Intraday repricing of D's own implied move lives
    in the "Implied move over time" section above.

    Open, high, low, and actual (close) are all measured against that
    same reference snapshot's spot, signed (down = negative), forming a
    standard OHLC candle per session:

    * open / high / low = official market values from Robinhood when
      reachable (``ohlc_source == "market"``); otherwise derived from
      every snapshot captured on D regardless of expiration
      (``ohlc_source == "snapshots"``). The snapshot fallback is sampled
      at the batch cadence: a late scheduler start makes the first
      snapshot masquerade as the open, and extremes between fires are
      invisible.
    * actual = last spot captured on D (the session "close" for past
      days; the latest print for today). Stays snapshot-based even when
      market data is available, so today's candle keeps updating on the
      same clock as the rest of the dashboard; the high/low are clamped
      to include it. Days with market data but zero snapshots fall back
      to the official close.

    One dict per day, oldest → newest:
        {"day", "implied" ({conf: pct} or None), "actual_pct",
         "open_pct", "high_pct", "low_pct",
         "open_spot", "high_spot", "low_spot", "ohlc_source",
         "ref_spot", "close_spot", "iv", "days_to_exp",
         "implied_captured_at_local", "close_captured_at_local",
         "open_captured_at_local"}
    """
    end = date.fromisoformat(end_iso)
    days = _past_business_days(end, num_days)

    # Official market OHLC (empty dict when Robinhood is unreachable).
    # Snapshot-derived values are only the fallback: a late scheduler
    # start makes the first snapshot masquerade as the open, and highs/
    # lows between fires are missed entirely.
    market_ohlc = _market_daily_ohlc(ticker, end_iso)

    # Spot path per day from ALL snapshots of the ticker. limit=10000
    # covers ~2000 batch fires — far more than the deepest window shown.
    spots_by_day: dict[date, list[tuple[datetime, float]]] = {}
    for r in gex_store.recent_snapshots(ticker=ticker, limit=10000):
        local_dt = _parse_utc(r["captured_at"]).astimezone()
        if days[0] <= local_dt.date() <= days[-1]:
            spots_by_day.setdefault(local_dt.date(), []).append(
                (local_dt, float(r["spot_price"]))
            )

    out: list[dict] = []
    for day in days:
        rows = gex_store.recent_snapshots(
            ticker=ticker, expiration_date=day.isoformat(), limit=500
        )
        # rows are newest → oldest, so the first row captured before the
        # day boundary is the prior session's latest snapshot.
        ref = None
        for r in rows:
            local_dt = _parse_utc(r["captured_at"]).astimezone()
            if local_dt.date() < day:
                ref = (r, local_dt)
                break

        entry: dict = {
            "day": day,
            "implied": None,
            "actual_pct": None,
            "open_pct": None,
            "high_pct": None,
            "low_pct": None,
            "open_spot": None,
            "high_spot": None,
            "low_spot": None,
            "ref_spot": None,
            "close_spot": None,
            "iv": None,
            "days_to_exp": None,
            "implied_captured_at_local": None,
            "close_captured_at_local": None,
            "open_captured_at_local": None,
        }
        if ref is not None:
            r, local_dt = ref
            spot = float(r["spot_price"])
            iv = _atm_iv_from_strikes(gex_store.get_strikes(r["id"]), spot)
            days_to_exp = _business_days_between(local_dt.date(), day)
            if iv is not None and days_to_exp > 0:
                entry["implied"] = {
                    conf: iv * math.sqrt(days_to_exp / 252.0) * Z_BY_CONF[conf] * 100.0
                    for conf, _, _ in IMPLIED_MOVE_LEVELS
                }
                entry["ref_spot"] = spot
                entry["iv"] = iv
                entry["days_to_exp"] = days_to_exp
                entry["implied_captured_at_local"] = local_dt

        day_spots = spots_by_day.get(day, [])
        market = market_ohlc.get(day.isoformat())
        entry["ohlc_source"] = "snapshots"
        if entry["ref_spot"] is not None and (day_spots or market):
            ref_spot = entry["ref_spot"]

            def _pct(spot: float) -> float:
                return (spot - ref_spot) / ref_spot * 100.0

            if day_spots:
                open_dt, open_spot = min(day_spots, key=lambda p: p[0])
                close_dt, close_spot = max(day_spots, key=lambda p: p[0])
                entry["open_spot"] = open_spot
                entry["open_captured_at_local"] = open_dt
                entry["close_spot"] = close_spot
                entry["close_captured_at_local"] = close_dt
                entry["high_spot"] = max(s for _dt, s in day_spots)
                entry["low_spot"] = min(s for _dt, s in day_spots)

            if market:
                # Official open/high/low replace the snapshot-sampled
                # ones. The close stays snapshot-based when snapshots
                # exist (it's the value the implied bands are scored
                # against, and hover cites its capture time); clamp the
                # range so the candle stays well-formed either way.
                entry["open_spot"] = market["open"]
                entry["open_captured_at_local"] = None
                if entry["close_spot"] is None:
                    entry["close_spot"] = market["close"]
                entry["high_spot"] = max(market["high"], entry["close_spot"])
                entry["low_spot"] = min(market["low"], entry["close_spot"])
                entry["ohlc_source"] = "market"

            entry["actual_pct"] = _pct(entry["close_spot"])
            entry["open_pct"] = _pct(entry["open_spot"])
            entry["high_pct"] = _pct(entry["high_spot"])
            entry["low_pct"] = _pct(entry["low_spot"])
        out.append(entry)
    return out


def _render_implied_vs_actual_chart(ticker: str, history: list[dict]) -> None:
    if not any(
        h["implied"] is not None or h["actual_pct"] is not None for h in history
    ):
        st.info(
            f"No history yet for {ticker} on these days. Each completed "
            "session needs a snapshot from the prior day (for the implied "
            "move) and one during the session itself (for the actual move)."
        )
        return

    today = date.today()
    labels = [
        f"{h['day'].strftime('%b %d')} "
        + ("(today)" if h["day"] == today else f"({h['day'].strftime('%a')})")
        for h in history
    ]

    fig = go.Figure()

    # Implied bands: symmetric ±σ lines. The negative twin shares a
    # legend group so one legend click toggles both sides.
    for i, (conf, label, color) in enumerate(IMPLIED_MOVE_LEVELS):
        vals = [h["implied"][conf] if h["implied"] else None for h in history]
        customdata = [
            [
                h["implied"][conf] if h["implied"] else 0.0,
                h["ref_spot"] or 0.0,
                (h["iv"] or 0.0) * 100,
                h["implied_captured_at_local"].strftime("%b %d %H:%M")
                if h["implied_captured_at_local"] else "n/a",
            ]
            for h in history
        ]
        if i == 0:
            hover = (
                "Priced from snapshot <b>%{customdata[3]}</b>  ·  "
                "ref spot <b>$%{customdata[1]:.2f}</b>  ·  "
                "ATM IV <b>%{customdata[2]:.1f}%</b><br>"
                f"±{label} implied: <b>±%{{customdata[0]:.2f}}%</b>"
                "<extra></extra>"
            )
        else:
            hover = (
                f"±{label} implied: <b>±%{{customdata[0]:.2f}}%</b>"
                "<extra></extra>"
            )
        fig.add_trace(go.Scatter(
            x=labels, y=vals,
            mode="lines+markers",
            name=f"±{label} implied",
            legendgroup=f"sigma{i}",
            line=dict(color=color, width=2, dash="dot"),
            marker=dict(size=8, color=color),
            connectgaps=False,
            customdata=customdata,
            hovertemplate=hover,
        ))
        fig.add_trace(go.Scatter(
            x=labels,
            y=[-v if v is not None else None for v in vals],
            mode="lines+markers",
            legendgroup=f"sigma{i}",
            showlegend=False,
            line=dict(color=color, width=2, dash="dot"),
            marker=dict(size=8, color=color),
            connectgaps=False,
            hoverinfo="skip",
        ))

    # Traditional candlestick per session: body = open→close, wicks =
    # high/low — everything in % of the prior-session reference spot, so
    # 0% is where yesterday's snapshot left off.
    #
    # Hollow vs filled (classic open/close cue):
    #   * hollow green  = close ≥ open (open was lower — buyers won)
    #   * filled red    = close <  open (open was higher — sellers won)
    # Color alone wasn't enough to make O vs C obvious; the empty/filled
    # body matches what TradingView / most charting apps do.
    #
    # Candlestick traces don't support hovertemplate, so the $ context
    # rides along as `text`, appended after the default O/H/L/C readout.
    candle_text = []
    for h in history:
        if h["actual_pct"] is None or h["ref_spot"] is None:
            candle_text.append("")
            continue
        src = h.get("ohlc_source", "snapshots")
        src_note = (
            "OHLC from market"
            if src == "market"
            else "OHLC from snapshots (no market data)"
        )
        close_note = (
            f"last snapshot {h['close_captured_at_local']:%b %d %H:%M}"
            if h["close_captured_at_local"] is not None
            else "official close"
        )
        oc = (
            "hollow (close ≥ open)"
            if h["actual_pct"] >= h["open_pct"]
            else "filled (close < open)"
        )
        candle_text.append(
            f"ref ${h['ref_spot']:.2f} → close ${h['close_spot']:.2f}  "
            f"(actual {h['actual_pct']:+.2f}% vs prior session)<br>"
            f"O ${h['open_spot']:.2f} · H ${h['high_spot']:.2f} · "
            f"L ${h['low_spot']:.2f}  ·  {oc}  ·  {close_note}  ·  {src_note}"
        )
    fig.add_trace(go.Candlestick(
        x=labels,
        open=[h["open_pct"] for h in history],
        high=[h["high_pct"] for h in history],
        low=[h["low_pct"] for h in history],
        close=[h["actual_pct"] for h in history],
        name="Session (O/H/L/C)",
        increasing=dict(
            # Hollow body — transparent fill, green border + wick.
            line=dict(color="#2ca02c", width=2),
            fillcolor="rgba(0, 0, 0, 0)",
        ),
        decreasing=dict(
            # Solid body — filled red.
            line=dict(color="#d62728", width=2),
            fillcolor="#d62728",
        ),
        text=candle_text,
    ))

    fig.add_hline(y=0, line_color="#999", line_width=1)
    # Longer windows pack more candles on x — grow the plot so wicks /
    # σ bands stay readable (5d ≈ 560px, 20d ≈ 800px).
    n = max(len(history), 1)
    chart_h = int(min(900, max(560, 400 + 20 * n)))
    fig.update_layout(
        title=f"{ticker} — implied (from prior session) vs actual daily move",
        xaxis_title="Session",
        yaxis_title="Move (% of prior-session spot)",
        height=chart_h,
        hovermode="x unified",
        legend=dict(orientation="h", y=1.08, x=0),
        margin=dict(t=70, l=60, r=20, b=50),
        xaxis_rangeslider_visible=False,
    )
    fig.update_xaxes(type="category")
    fig.update_yaxes(ticksuffix="%", tickformat="+.2f")

    st.plotly_chart(fig, use_container_width=True)

    scored = [
        h for h in history
        if h["actual_pct"] is not None and h["implied"] is not None
    ]
    # Today isn't over — its close can still walk in or out of the bands,
    # so the hit-rate stats only count finished sessions.
    completed = [h for h in scored if h["day"] < today]
    col_a, col_b, col_c, col_d = st.columns(4)
    conf1, conf2 = IMPLIED_MOVE_LEVELS[0][0], IMPLIED_MOVE_LEVELS[1][0]
    with col_a:
        if completed:
            n1 = sum(
                1 for h in completed if abs(h["actual_pct"]) <= h["implied"][conf1]
            )
            st.metric(
                "Days within ±1σ",
                f"{n1}/{len(completed)}",
                help=(
                    "Completed sessions only (today excluded). If the "
                    "options market prices risk correctly, ~68% of "
                    "sessions should land inside the 1σ band."
                ),
            )
        else:
            st.metric("Days within ±1σ", "n/a")
    with col_b:
        if completed:
            n2 = sum(
                1 for h in completed if abs(h["actual_pct"]) <= h["implied"][conf2]
            )
            st.metric(
                "Days within ±2σ",
                f"{n2}/{len(completed)}",
                help=(
                    "Completed sessions only (today excluded). ~95% of "
                    "sessions should land inside the 2σ band."
                ),
            )
        else:
            st.metric("Days within ±2σ", "n/a")
    with col_c:
        if scored:
            last = scored[-1]
            is_live = last["day"] == today
            title = (
                "Today so far (live)" if is_live
                else f"Last session ({last['day'].strftime('%b %d')})"
            )
            st.metric(
                title,
                f"{last['actual_pct']:+.2f}%",
                f"±{last['implied'][conf1]:.2f}% was 1σ implied",
                delta_color="off",
                help=(
                    "Today's number moves with each new snapshot; the "
                    "implied band it's judged against stays frozen at "
                    "the prior session's close."
                ) if is_live else None,
            )
        else:
            st.metric("Last session", "n/a")
    with col_d:
        if scored:
            big = max(scored, key=lambda h: abs(h["actual_pct"]))
            st.metric(
                "Biggest move",
                f"{big['actual_pct']:+.2f}%",
                big["day"].strftime("%b %d"),
                delta_color="off",
            )
        else:
            st.metric("Biggest move", "n/a")


# ---------------------------------------------------------------------------
# Today's most likely scenario — historical pattern matching
# ---------------------------------------------------------------------------

# How far back to scan for pattern occurrences. Days with no data are
# skipped cheaply, so this is an upper bound, not a requirement.
_PATTERN_SCAN_SESSIONS = 60

_BUCKET_LABELS = {1: "under ±1σ", 2: "±1σ–±2σ", 3: "beyond ±2σ"}
_ANSWER_LABELS = {1: "under ±1σ", 2: "under ±2σ", 3: "under ±3σ"}


def _sigma_bucket(actual_pct: float, implied_1sigma_pct: float) -> int:
    """1 = moved under ±1σ, 2 = between ±1σ and ±2σ, 3 = beyond ±2σ."""
    az = abs(actual_pct) / implied_1sigma_pct
    if az <= 1.0:
        return 1
    if az <= 2.0:
        return 2
    return 3


def _pattern_prediction(
    history: list[dict], today: date, max_matches: int,
) -> dict | None:
    """Predict today's sigma bucket purely from historical patterns.

    Method — no distributional model, just counting what happened:

    1. Bucket every completed session by how it moved vs its own
       prior-session implied band: under ±1σ / ±1–2σ / beyond ±2σ.
    2. The "pattern" is the buckets of the two most recent completed
       sessions (e.g. yesterday under ±1σ, the day before ±1–2σ).
    3. Walk back through history for the most recent times that same
       two-session pattern appeared (up to ``max_matches``) and record
       what the *next* day did each time.
    4. The most frequent outcome is the call; its share of the matches
       is the probability. Ties break toward the calmer bucket.

    Fallbacks when the DB is young: if the two-session pattern has
    fewer than 3 occurrences, match on yesterday's bucket alone; if
    even that is thin, use the outcome distribution of all completed
    sessions. ``basis`` reports which level answered.

    Returns None with fewer than 3 completed sessions total.
    """
    conf1 = IMPLIED_MOVE_LEVELS[0][0]
    completed = [
        h for h in history
        if h["day"] < today
        and h["actual_pct"] is not None
        and h["implied"] is not None
    ]
    if len(completed) < 3:
        return None

    buckets = [
        (h["day"], _sigma_bucket(h["actual_pct"], h["implied"][conf1]))
        for h in completed
    ]  # oldest → newest

    pattern = (buckets[-2][1], buckets[-1][1])
    pattern_days = (buckets[-2][0], buckets[-1][0])

    # Most recent matches first. The current pattern itself sits at
    # i = len-2 and has no outcome yet, so scanning stops at len-3.
    matches: list[tuple[date, int]] = []
    for i in range(len(buckets) - 3, -1, -1):
        if (buckets[i][1], buckets[i + 1][1]) == pattern:
            matches.append(buckets[i + 2])
        if len(matches) == max_matches:
            break
    basis = "two-session pattern"

    if len(matches) < 3:
        matches = []
        for i in range(len(buckets) - 2, -1, -1):
            if buckets[i][1] == pattern[1]:
                matches.append(buckets[i + 1])
            if len(matches) == max_matches:
                break
        basis = "yesterday's bucket only (two-session pattern too rare)"

    if len(matches) < 3:
        matches = list(reversed(buckets))[:max_matches]
        basis = "overall distribution (patterns too rare in this history)"

    counts = Counter(b for _d, b in matches)
    # max count, ties to the calmer bucket
    prediction = min(
        (k for k in (1, 2, 3) if counts.get(k, 0) == max(counts.values())),
    )
    prob = counts[prediction] / len(matches)

    out: dict = {
        "pattern": pattern,
        "pattern_days": pattern_days,
        "matches": matches,
        "counts": counts,
        "prediction": prediction,
        "prob": prob,
        "basis": basis,
        "today_implied1": None,
        "today_ref_spot": None,
        "today_actual_pct": None,
    }
    if history and history[-1]["day"] == today:
        t = history[-1]
        if t["implied"] is not None:
            out["today_implied1"] = t["implied"][conf1]
            out["today_ref_spot"] = t["ref_spot"]
            out["today_actual_pct"] = t["actual_pct"]
    return out


def _render_pattern_prediction(
    ticker: str, history: list[dict], max_matches: int,
) -> None:
    today = date.today()
    res = _pattern_prediction(history, today, max_matches)
    if res is None:
        st.info(
            f"Not enough history for {ticker} — the prediction needs at "
            "least 3 completed sessions with both an implied band and an "
            "actual move."
        )
        return

    k = res["prediction"]
    n = len(res["matches"])
    st.metric(
        f"{ticker} — most likely today",
        _ANSWER_LABELS[k],
        f"{res['prob'] * 100:.0f}% probability "
        f"({res['counts'][k]} of {n} matches)",
        delta_color="off",
    )

    d1, d2 = res["pattern_days"]
    b1, b2 = res["pattern"]
    dist = "  ·  ".join(
        f"{_BUCKET_LABELS[b]} ×{res['counts'][b]}"
        for b in (1, 2, 3) if res["counts"].get(b, 0) > 0
    )
    lines = [
        f"Pattern observed: **{d1:%b %d}** moved {_BUCKET_LABELS[b1]}, "
        f"**{d2:%b %d}** moved {_BUCKET_LABELS[b2]}. "
        f"Matched on: {res['basis']}. "
        f"Next-day outcomes across those {n} matches: {dist}."
    ]
    if res["today_implied1"] is not None and res["today_ref_spot"]:
        imp1 = res["today_implied1"]
        ref = res["today_ref_spot"]
        band = imp1 * k
        lines.append(
            f"Today's ±{k}σ band (frozen from the prior session): "
            f"**±{band:.2f}%** of ${ref:.2f} → "
            f"**${ref * (1 - band / 100.0):.2f} – "
            f"${ref * (1 + band / 100.0):.2f}**."
        )
        if res["today_actual_pct"] is not None:
            so_far = abs(res["today_actual_pct"]) / imp1
            lines.append(
                f"So far today: {res['today_actual_pct']:+.2f}% "
                f"= {so_far:.2f}σ."
            )
    st.caption("  ".join(lines))


def _crossing_history(
    ticker: str, expiration: date, range_pct: float = 5.0,
) -> list[dict]:
    """For each snapshot of (ticker, expiration), compute the cumulative
    dollar-OI crossing strike and pair it with the spot at that moment.

    ``range_pct`` MUST match what the PNG uses (default 5.0 = ±5% of
    spot) or the values won't line up. Passing ``0`` includes the whole
    chain — which lets deep-OTM long-tail OI dominate the crossing and
    produces a wildly different (and much less meaningful) number.

    Returns a list of dicts sorted oldest → newest so plotting is a
    straight time series. Skips snapshots that don't have enough data to
    compute a crossing (e.g. one-sided chains).
    """
    rows = gex_store.recent_snapshots(
        ticker=ticker, expiration_date=expiration.isoformat(), limit=500
    )
    if not rows:
        return []

    history: list[dict] = []
    for r in rows:
        df = _load_oi_snapshot_df(r)
        if df is None or df.empty:
            continue
        spot = float(r["spot_price"])
        series = _prepare_oi_series(
            df, spot=spot, metric="dollars", range_pct=range_pct,
        )
        if series is None:
            continue
        call_cum = np.cumsum(series["call_vals"])
        put_arr = np.array(series["put_vals_positive"])
        put_cum = np.cumsum(put_arr[::-1])[::-1]
        cx, cy = _find_curve_crossing(series["strikes"], call_cum, put_cum)
        if cx is None:
            continue
        history.append({
            "captured_at_utc": _parse_utc(r["captured_at"]),
            "captured_at_local": _parse_utc(r["captured_at"]).astimezone(),
            "crossing_strike": float(cx),
            "crossing_dollars": float(cy) if cy is not None else None,
            "spot_price": spot,
        })

    history.sort(key=lambda h: h["captured_at_utc"])
    return history


