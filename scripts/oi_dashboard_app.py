def _today_price_series(ticker: str, today: date) -> list[dict]:
    """Best-available price path for today, oldest → newest.

    Poller ticks at full sub-minute resolution wherever they exist;
    minutes with no tick fall back to the per-minute path (Robinhood
    5-minute bars, then batch snapshots), so a late poller start still
    shows the whole session. Timestamps are naive local (ET).
    """
    ticks = daily_moves_store.get_ticks(ticker, today)
    covered: set[int] = set()
    series: list[dict] = []
    for t in ticks:
        covered.add(daily_moves_store.minutes_from_open(t["ts"]))
        series.append({
            "ts": t["ts"].astimezone().replace(tzinfo=None),
            "price": t["price"],
            "source": "tick",
        })
    for p in daily_moves_store.get_session_path(ticker, today):
        if p["source"] == "tick" or p["minutes_from_open"] in covered:
            continue
        series.append({
            "ts": _minute_to_dt(today, p["minutes_from_open"]),
            "price": p["spot"],
            "source": p["source"],
        })
    series.sort(key=lambda e: e["ts"])
    return series


