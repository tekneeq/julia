def _parse_utc(iso_ts: str) -> datetime:
    return datetime.fromisoformat(iso_ts.replace("Z", "+00:00"))


# ---------------------------------------------------------------------------
# Implied-move time series (68% / 95% / 99.7%)
# ---------------------------------------------------------------------------

# Same three levels the `emove` CLI prints. Tuple: (confidence, label, color).
IMPLIED_MOVE_LEVELS: list[tuple[float, str, str]] = [
    (0.6827, "68% (1σ)", "#1f77b4"),
    (0.9545, "95% (2σ)", "#ff7f0e"),
    (0.9973, "99.7% (3σ)", "#d62728"),
]
Z_BY_CONF: dict[float, float] = {
    conf: float(norm.ppf((1 + conf) / 2)) for conf, _, _ in IMPLIED_MOVE_LEVELS
}


def _business_days_between(start: date, end: date) -> int:
    """Trading-day count between ``start`` (exclusive) and ``end`` (inclusive).

    Matches the convention `emove` uses in ``sqrt(days / 252)``. Returns
    0 if ``end`` <= ``start`` (same-day or already-expired snapshot).
    """
    if end <= start:
        return 0
    d, count = start, 0
    while d < end:
        d += timedelta(days=1)
        if d.weekday() < 5:  # Mon=0..Fri=4
            count += 1
    return count


def _atm_iv_from_strikes(strikes, spot: float) -> float | None:
    """Average of call & put IV at the strike closest to spot.

    Returns ``None`` if we can't find a usable IV (illiquid chain,
    missing data). We snap to the nearest strike rather than
    interpolating because the strike grid is dense enough (usually $1
    for SPY) that interpolation adds noise, not accuracy.
    """
    if not strikes:
        return None
    # Find strike closest to spot
    nearest = min(strikes, key=lambda r: abs(float(r["strike_price"]) - spot))
    target_strike = float(nearest["strike_price"])

    ivs: list[float] = []
    for r in strikes:
        if abs(float(r["strike_price"]) - target_strike) > 1e-9:
            continue
        iv = r["implied_vol"]
        if iv is not None and iv > 0:
            ivs.append(float(iv))
    if not ivs:
        return None
    return sum(ivs) / len(ivs)


# Target tenor for the ticker-level IV series that feeds IV Rank.
# ~30 calendar days is the conventional "front" IV used by IV-rank
# screens; we pick whichever expiration that day was closest to it.
_IV_RANK_TARGET_DTE = 30
_IV_RANK_LOOKBACK_DAYS = 365  # calendar days of snapshot history to scan


@st.cache_data(ttl=120, show_spinner=False)
def _ticker_daily_atm_iv(ticker: str) -> list[tuple[date, float]]:
    """One ATM IV per local trading day for ``ticker``.

    For each day, among every snapshot fired that day, keep the one
    whose expiration is closest to ``capture + 30 calendar days``
    (DTE ≥ 1 required), then take that chain's ATM IV. Returns
    oldest → newest. Empty when the DB has nothing yet.
    """
    cutoff = date.today() - timedelta(days=_IV_RANK_LOOKBACK_DAYS)
    rows = gex_store.recent_snapshots(ticker=ticker, limit=10000)
    # local_date → (distance_to_target_dte, captured_at, snapshot_row)
    best: dict[date, tuple[int, datetime, object]] = {}
    for r in rows:
        local_dt = _parse_utc(r["captured_at"]).astimezone()
        d = local_dt.date()
        if d < cutoff:
            continue
        try:
            exp = date.fromisoformat(r["expiration_date"])
        except ValueError:
            continue
        dte = (exp - d).days
        if dte < 1:
            continue
        dist = abs(dte - _IV_RANK_TARGET_DTE)
        prev = best.get(d)
        # Prefer closer-to-30-DTE; on a tie keep the later snapshot.
        if (
            prev is None
            or dist < prev[0]
            or (dist == prev[0] and local_dt > prev[1])
        ):
            best[d] = (dist, local_dt, r)

    out: list[tuple[date, float]] = []
    for d in sorted(best):
        _dist, _ts, r = best[d]
        iv = _atm_iv_from_strikes(
            gex_store.get_strikes(r["id"]), float(r["spot_price"])
        )
        if iv is not None:
            out.append((d, iv))
    return out


def _iv_rank(current_iv: float, daily: list[tuple[date, float]]) -> dict:
    """Standard IV Rank of ``current_iv`` against a daily ATM-IV series.

    IV Rank = (current − min) / (max − min) × 100 over the series.
    0 = at the lookback low, 100 = at the lookback high. Returns
    ``rank=None`` when the series is empty or flat (max == min).
    """
    if not daily:
        return {"rank": None, "n": 0, "lo": None, "hi": None}
    ivs = [iv for _d, iv in daily]
    # Fold the live reading into the range so a brand-new high/low
    # registers as 100 / 0 rather than extrapolating past the series.
    lo = min(min(ivs), current_iv)
    hi = max(max(ivs), current_iv)
    n = len(ivs)
    if hi - lo < 1e-9:
        return {"rank": None, "n": n, "lo": lo, "hi": hi}
    return {
        "rank": (current_iv - lo) / (hi - lo) * 100.0,
        "n": n,
        "lo": lo,
        "hi": hi,
    }


@st.cache_data(ttl=60, show_spinner=False)
def _implied_move_history(ticker: str, expiration_iso: str) -> list[dict]:
    """For each snapshot of (ticker, expiration), compute implied moves
    at 68%, 95%, and 99.7% confidence.

    Cached (60s TTL) because this hits ``get_strikes`` once per snapshot
    — non-trivial cost when the DB has hundreds of rows.

    Returned dicts include both $ and % moves per confidence level,
    plus the ATM IV that drove them (useful for the metric card).
    Sorted oldest → newest.
    """
    exp = date.fromisoformat(expiration_iso)
    rows = gex_store.recent_snapshots(
        ticker=ticker, expiration_date=expiration_iso, limit=500
    )
    if not rows:
        return []

    history: list[dict] = []
    for r in rows:
        spot = float(r["spot_price"])
        local_dt = _parse_utc(r["captured_at"]).astimezone()
        days = _business_days_between(local_dt.date(), exp)
        if days <= 0:
            continue  # expired / same-day
        strikes = gex_store.get_strikes(r["id"])
        iv = _atm_iv_from_strikes(strikes, spot)
        if iv is None:
            continue

        entry = {
            "captured_at_utc": _parse_utc(r["captured_at"]),
            "captured_at_local": local_dt,
            "spot": spot,
            "iv": iv,
            "days": days,
        }
        for conf, _, _ in IMPLIED_MOVE_LEVELS:
            move_dollars = spot * iv * math.sqrt(days / 252.0) * Z_BY_CONF[conf]
            entry[f"move_dollars_{conf}"] = move_dollars
            entry[f"move_pct_{conf}"] = (move_dollars / spot) * 100.0
        history.append(entry)

    history.sort(key=lambda h: h["captured_at_utc"])
    return history


def _render_implied_move_chart(
    ticker: str, expiration: date, history: list[dict], unit: str,
) -> None:
    """Render implied-move time series with 3 confidence bands.

    ``unit`` is either ``"pct"`` (Y-axis in % of spot) or ``"dollars"``
    (Y-axis in $). % is more comparable across expirations; $ is more
    concrete when comparing to spot moves.
    """
    if not history:
        st.info(
            f"No snapshots yet for {ticker} {expiration.isoformat()}. "
            "Run **oi-dashboard** at least once to seed the history."
        )
        return

    ts = [h["captured_at_local"] for h in history]
    single = len(history) == 1
    key = "move_pct" if unit == "pct" else "move_dollars"

    fig = go.Figure()
    for i, (conf, label, color) in enumerate(IMPLIED_MOVE_LEVELS):
        vals = [h[f"{key}_{conf}"] for h in history]
        # customdata rows: [spot, low_bound, high_bound, iv_pct,
        #                   move_pct, move_dollars, days]
        customdata = [
            [
                h["spot"],
                h["spot"] - h[f"move_dollars_{conf}"],
                h["spot"] + h[f"move_dollars_{conf}"],
                h["iv"] * 100,
                h[f"move_pct_{conf}"],
                h[f"move_dollars_{conf}"],
                h["days"],
            ]
            for h in history
        ]
        # Only the first trace shows the shared context (spot, IV, days
        # to expiry). Subsequent traces show only their specific move
        # info, so `hovermode="x unified"` doesn't repeat spot 3 times.
        if i == 0:
            hover = (
                "Spot at snapshot: <b>$%{customdata[0]:.2f}</b>  "
                "·  ATM IV <b>%{customdata[3]:.1f}%</b>  "
                "·  <b>%{customdata[6]}d</b> to exp<br>"
                f"±{label}: <b>±%{{customdata[4]:.2f}}%</b>  "
                "(±$%{customdata[5]:.2f})  →  "
                "<b>$%{customdata[1]:.2f} / $%{customdata[2]:.2f}</b>"
                "<extra></extra>"
            )
        else:
            hover = (
                f"±{label}: <b>±%{{customdata[4]:.2f}}%</b>  "
                "(±$%{customdata[5]:.2f})  →  "
                "<b>$%{customdata[1]:.2f} / $%{customdata[2]:.2f}</b>"
                "<extra></extra>"
            )
        fig.add_trace(go.Scatter(
            x=ts, y=vals,
            mode="markers" if single else "lines+markers",
            name=f"±{label}",
            line=dict(color=color, width=2.5),
            marker=dict(size=12 if single else 7, color=color),
            customdata=customdata,
            hovertemplate=hover,
        ))

    last = history[-1]
    days_note = f"{last['days']} trading day{'s' if last['days'] != 1 else ''} to expiry"
    fig.update_layout(
        title=(
            f"{ticker} {expiration.isoformat()} — implied move  "
            f"·  {len(history)} snapshot{'s' if len(history) != 1 else ''}  "
            f"·  {days_note} (at latest snapshot)"
        ),
        xaxis_title="Snapshot time (local)",
        yaxis_title=("Implied move (% of spot)" if unit == "pct" else "Implied move ($)"),
        height=380,
        hovermode="x unified",
        legend=dict(orientation="h", y=1.08, x=0),
        margin=dict(t=60, l=60, r=20, b=40),
    )
    if unit == "pct":
        fig.update_yaxes(ticksuffix="%")
    else:
        fig.update_yaxes(tickprefix="$")
    if single:
        t0 = ts[0]
        fig.update_xaxes(range=[t0 - timedelta(hours=6), t0 + timedelta(hours=6)])

    st.plotly_chart(fig, use_container_width=True)

    first = history[0]
    d_iv = last["iv"] - first["iv"]
    col_a, col_b, col_c, col_d, col_e = st.columns(5)
    for col, (conf, label, _color) in zip((col_a, col_b, col_c), IMPLIED_MOVE_LEVELS):
        with col:
            latest_val = last[f"{key}_{conf}"]
            latest_dollars = last[f"move_dollars_{conf}"]
            latest_pct = last[f"move_pct_{conf}"]
            if unit == "pct":
                headline = f"±{latest_val:.2f}%"
                sub = f"±${latest_dollars:.2f}"
            else:
                headline = f"±${latest_val:.2f}"
                sub = f"±{latest_pct:.2f}%"
            if not single:
                delta = latest_val - first[f"{key}_{conf}"]
                sign = "+" if delta >= 0 else ""
                sub = f"{sub}   ({sign}{delta:.2f} vs first)"
            st.metric(f"Latest {label}", headline, sub)
    with col_d:
        st.metric(
            "ATM IV (annualized)",
            f"{last['iv']*100:.1f}%",
            None if single else f"{d_iv*100:+.2f}pp vs first",
            help=(
                "Annualized at-the-money implied volatility for this "
                "expiration, driving the moves above. Rising = market "
                "pricing in more uncertainty; falling = vol crush. "
                "Spikes into events (FOMC, CPI, earnings), decays "
                "afterward."
            ),
        )
    with col_e:
        # IV Rank is a ticker-level reading (≈30-DTE ATM IV over the
        # snapshot history), shown next to this expiration's ATM IV so
        # you can tell whether today's vol is cheap or rich vs recent
        # range — not a rank of this single expiration alone.
        daily_iv = _ticker_daily_atm_iv(ticker)
        # Prefer the series' own latest IV as "current" so the rank and
        # its lookback share one methodology; fall back to this
        # expiration's ATM IV when the series is empty.
        current_for_rank = daily_iv[-1][1] if daily_iv else last["iv"]
        rank_info = _iv_rank(current_for_rank, daily_iv)
        if rank_info["rank"] is None:
            st.metric(
                "IV Rank",
                "n/a",
                (
                    f"need more history ({rank_info['n']} day"
                    f"{'s' if rank_info['n'] != 1 else ''})"
                ),
                help=(
                    "IV Rank = (current − min) / (max − min) over the "
                    "ticker's daily ≈30-DTE ATM IV from your snapshots. "
                    "Needs at least two distinct IV levels in the "
                    "lookback to compute."
                ),
            )
        else:
            lo_pct = rank_info["lo"] * 100
            hi_pct = rank_info["hi"] * 100
            st.metric(
                "IV Rank",
                f"{rank_info['rank']:.0f}",
                f"≈30D ATM {current_for_rank * 100:.1f}%  ·  "
                f"{rank_info['n']}d  ·  {lo_pct:.1f}–{hi_pct:.1f}%",
                help=(
                    "Where the ticker's ≈30-DTE ATM IV sits between its "
                    "lookback low (0) and high (100), from your snapshot "
                    "history. Low rank = vol is cheap vs recent range; "
                    "high rank = expensive. Distinct from this "
                    "expiration's ATM IV on the left — that number is "
                    "tenor-specific; IV Rank is the ticker regime. "
                    f"Current ≈30D ATM = {current_for_rank * 100:.1f}%, "
                    f"range {lo_pct:.1f}–{hi_pct:.1f}% over "
                    f"{rank_info['n']} days."
                ),
            )
    if single:
        st.caption(
            "Only one snapshot so far — as new snapshots arrive, this "
            "will show how the market's own uncertainty is repricing "
            "throughout the day."
        )


