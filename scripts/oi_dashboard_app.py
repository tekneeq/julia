def _chicklet_zero_window(
    high_pct: float,
    low_pct: float,
    implied: dict | None,
) -> tuple[float, float, list[tuple[float, str]]]:
    """Symmetric y-window around 0% (prior close), plus any touched σ lines.

    * 0% is always the vertical midpoint — so a gap-up open is obvious.
    * Extent is ``max(|high|, |low|)`` of the day's path (small pad),
      so every card is uniform: prior close centered, day's extremes
      set the scale.
    * A σ line is drawn only if the path actually reached it
      (high ≥ +σ or low ≤ −σ). Untouched bands stay off.
    """
    extent = max(abs(high_pct), abs(low_pct), 0.15)
    pad = max(extent * 0.08, 0.05)
    y_max = extent + pad
    y_min = -extent - pad

    levels: list[tuple[float, str]] = []
    if implied:
        for conf, _label, color in IMPLIED_MOVE_LEVELS:
            s = implied.get(conf)
            if s is None or s <= 0:
                continue
            s = float(s)
            if high_pct + 1e-9 >= s:
                levels.append((+s, color))
            if low_pct - 1e-9 <= -s:
                levels.append((-s, color))
    return y_min, y_max, levels


def _session_chicklet_fig(
    day: date,
    path: list[dict],
    iva: dict | None,
    *,
    is_today: bool,
) -> go.Figure:
    """One compact session card: % path, O/H/L annotations, ±σ bands.

    Y-axis is always centered on 0% (prior close) and scaled to the
    day's high/low. σ lines appear only when the path touched them.
    """
    fig = go.Figure()
    implied = (iva or {}).get("implied") or None

    # O/H/L/close annotations and line color come from the path being
    # drawn so labels match the line. Sigma bands still come from
    # ``iva["implied"]`` (prior-session priced move).
    open_pct = high_pct = low_pct = close_pct = None

    if path:
        # Datetime x so hover/spike show clock time; pct rounded to 2dp.
        xs, clocks, ys = _path_clock_series(path, axis_day=day)
        open_pct = ys[0]
        high_pct = max(ys)
        low_pct = min(ys)
        close_pct = ys[-1]
        hi_i = max(range(len(ys)), key=lambda i: ys[i])
        lo_i = min(range(len(ys)), key=lambda i: ys[i])

        up = close_pct >= 0
        line_color = _TV_UP if up else _TV_DOWN
        fig.add_trace(go.Scatter(
            x=xs, y=ys,
            mode="lines",
            line=dict(color=line_color, width=1.6),
            fill="tozeroy",
            fillcolor=(_TV_UP_FILL if up else _TV_DOWN_FILL),
            customdata=clocks,
            hovertemplate="%{customdata} · <b>%{y:+.2f}%</b><extra></extra>",
            showlegend=False,
        ))

        fig.add_annotation(
            x=xs[0], y=open_pct, text=f"O {open_pct:+.2f}%",
            showarrow=False, xanchor="left", yanchor="bottom",
            font=dict(size=10, color=_TV_TEXT),
            xshift=2, yshift=2,
        )
        fig.add_annotation(
            x=xs[hi_i], y=high_pct, text=f"H {high_pct:+.2f}%",
            showarrow=False, xanchor="center", yanchor="bottom",
            font=dict(size=10, color=_TV_UP),
            yshift=4,
        )
        fig.add_annotation(
            x=xs[lo_i], y=low_pct, text=f"L {low_pct:+.2f}%",
            showarrow=False, xanchor="center", yanchor="top",
            font=dict(size=10, color=_TV_DOWN),
            yshift=-4,
        )
    else:
        fig.add_annotation(
            xref="paper", yref="paper", x=0.5, y=0.5,
            text="no path", showarrow=False,
            font=dict(size=11, color=_TV_MUTED),
        )

    # Always center on 0% (prior close). Empty cards get a neutral ±1%
    # window so the row stays aligned.
    sigma_levels: list[tuple[float, str]] = []
    if path and high_pct is not None and low_pct is not None:
        lo_y, hi_y, sigma_levels = _chicklet_zero_window(
            high_pct, low_pct, implied,
        )
    else:
        lo_y, hi_y = -1.0, 1.0

    # σ lines the path actually reached — nothing else.
    for signed, color in sigma_levels:
        fig.add_hline(
            y=signed,
            line_color=color,
            line_width=1,
            line_dash="dot",
            opacity=0.55,
        )
    # Prior-close baseline — always the vertical midpoint.
    fig.add_hline(y=0, line_color=_TV_MUTED, line_width=1.2)

    day_label = (
        f"Today · {day:%b %d}" if is_today else f"{day:%a %b %d}"
    )
    if close_pct is not None:
        day_label = f"{day_label}  {close_pct:+.2f}%"

    tick_mins = (0, 195, 390)
    tick_vals = [_minute_to_dt(day, m) for m in tick_mins]
    tick_text = ["9:30", "12:45", "4:00"]
    fig.update_layout(**_tv_layout(
        title=dict(
            text=day_label,
            font=dict(size=12, color=_TV_TEXT),
            x=0.02, xanchor="left",
        ),
        height=210,
        hovermode="x",
        showlegend=False,
        margin=dict(t=36, l=4, r=28, b=24),
        xaxis=dict(
            tickmode="array", tickvals=tick_vals, ticktext=tick_text,
            range=[
                _minute_to_dt(day, 0),
                _minute_to_dt(day, _SESSION_MINUTES),
            ],
            gridcolor=_TV_GRID,
            zeroline=False, color=_TV_MUTED, tickfont=dict(size=9),
            fixedrange=True,
            hoverformat="%-I:%M%p",
        ),
        yaxis=_pct_axis_layout(
            range=[lo_y, hi_y],
            tickfont=dict(size=9),
            fixedrange=True,
            nticks=5,
        ),
    ))
    return fig


def _render_recent_session_chiclets(ticker: str, today: date) -> None:
    """Prior 20 completed sessions as four rows of 5 compact % cards.

    Today is excluded — the live session chart above already covers it.
    Cards with no path yet render empty and fill in as the library
    densifies (market bars / ticks from the poller).
    """
    n_sessions = 20
    per_row = 5
    st.markdown("##### 📅 Last 20 sessions")
    st.caption(
        "The twenty most recent **completed** sessions (today excluded) "
        "as % vs each day's prior close — five per row, oldest → newest "
        "left-to-right then top-to-bottom. Annotated **O / H / L** are "
        "the open, high, and low of the move. Every card is centered on "
        "**0% (prior close)** and scaled symmetrically to that day's "
        "high/low — so a gap-up open is obvious and the row stays "
        "uniform. A ±σ line (blue / orange / red — same prior-session "
        "implied moves as **Implied vs actual daily moves**) is drawn "
        "only if the path actually reached it; untouched bands stay "
        "off. Empty cards mean no densified path yet; they fill in as "
        "history accumulates."
    )

    # Yesterday (or Friday if today is Mon / weekend) → nineteen more back.
    end = _prev_business_day(today)
    days = _past_business_days(end, n_sessions)
    iva = _implied_vs_actual_history(ticker, n_sessions, end.isoformat())
    iva_by_day = {h["day"]: h for h in iva}

    for row_start in range(0, n_sessions, per_row):
        row_days = days[row_start:row_start + per_row]
        cols = st.columns(per_row)
        for col, day in zip(cols, row_days):
            with col:
                path = daily_moves_store.get_session_path(ticker, day)
                _show_plotly(
                    _session_chicklet_fig(
                        day, path, iva_by_day.get(day),
                        is_today=False,
                    ),
                    config={"displayModeBar": False},
                )


def _render_today_twin_row(ticker: str, today: date) -> None:
    """Twins of *today so far* — continuation dashed after 'now'."""
    st.markdown("##### 🧬 Historical twins — today")
    st.caption(
        "The two completed sessions (of the last "
        f"{daily_moves_store.KEEP_SESSIONS}) whose intraday path most "
        "closely matches **today so far** — each on its own chart, in % "
        "vs that day's prior close. Thin grey = today; solid = the twin "
        "up to now; dashed = where that twin went after this time of day. "
        "Match score = recency-weighted RMSE, recomputed on every refresh."
    )
    result = _find_daily_twins(ticker, today, top_n=2)
    today_path = result["today_path"]
    if not today_path:
        st.info(
            "Twin matching starts once today has a path — it appears "
            "with the first few ticks or bars."
        )
        return
    if not result["twins"]:
        st.info(
            f"No comparable session yet — the library holds "
            f"{result['library_size']} completed sessions and none "
            "overlaps today's sample times."
        )
        return

    now_m = today_path[-1]["minutes_from_open"]
    last_pct = today_path[-1]["pct"]
    cols = st.columns(2)
    for i, twin in enumerate(result["twins"][:2]):
        with cols[i]:
            _show_plotly(
                _twin_fig(
                    ticker, today, today_path, twin,
                    i + 1, _TWIN_COLORS[i % len(_TWIN_COLORS)],
                ),
            )
            twin_now = _interpolate_pct(twin["path"], now_m)
            if twin_now is not None:
                st.caption(
                    f"At this time that day: **{twin_now:+.2f}%**  ·  "
                    f"today − twin = **{last_pct - twin_now:+.2f}pp**"
                )
    if len(result["twins"]) == 1:
        with cols[1]:
            st.info(
                "Only one comparable session in the library so far — a "
                "second twin appears as more history accumulates."
            )


def _render_yesterday_twin_row(ticker: str, today: date) -> None:
    """Yesterday vs its closest match (left) + that twin's next day (right)."""
    yesterday = _prev_business_day(today)
    st.markdown("##### 🧬 Historical twins — yesterday → next day")
    st.caption(
        f"**Left:** yesterday ({yesterday:%a %b %d}) overlaid with its "
        "single closest historical match. **Right:** only the next "
        "business day after that match — what happened the last time a "
        "similar session printed (e.g. if yesterday matched 7/23, the "
        "right chart is just 7/24)."
    )
    result = _find_path_twins(ticker, yesterday, top_n=1)
    ypath = result["query_path"]
    if not ypath:
        st.info(
            f"No path for yesterday ({yesterday:%b %d}) yet — it fills in "
            "once market bars / ticks densify that session."
        )
        return
    if not result["twins"]:
        st.info(
            f"No comparable session for yesterday — library holds "
            f"{result['library_size']} other sessions."
        )
        return

    twin = result["twins"][0]
    left, right = st.columns(2)
    with left:
        _show_plotly(
            _yesterday_match_fig(
                yesterday, ypath, twin, _TWIN_COLORS[0],
            ),
        )
        st.caption(
            f"Closest match **{twin['day']:%a %b %d}**  ·  "
            f"RMSE **{twin['rmse']:.2f}pp**"
            + (
                f"  ·  twin closed **{twin['final_pct']:+.2f}%**"
                if twin.get("final_pct") is not None else ""
            )
        )
    with right:
        _show_plotly(
            _nextday_only_fig(twin),
        )
        if twin.get("next_day") is not None and twin.get("next_final_pct") is not None:
            st.caption(
                f"After the twin on {twin['day']:%b %d}, "
                f"**{twin['next_day']:%a %b %d}** closed "
                f"**{twin['next_final_pct']:+.2f}%**"
            )
        else:
            st.caption(
                f"No next-day path after {twin['day']:%b %d} in the "
                "library yet."
            )


