"""Streamlit dashboard for `lia oi-dashboard` — live rolling view of the
current week's expirations.

Renders one column per expiration date across the next N business days
(default 5, starting today or the next business day if it's a weekend).
Auto-refreshes every 30s so any PNG regenerated by `oi_batch.py` — either
manually via the "Run batch now" button, or by a background cron — shows
up here without a page reload.

Run locally:

    UV_NATIVE_TLS=true uv run streamlit run scripts/oi_dashboard_app.py

Open in your browser at the URL Streamlit prints (usually
http://localhost:8501).
"""
