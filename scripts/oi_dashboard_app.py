def _next_business_day(d: date) -> date:
    while d.weekday() >= 5:
        d += timedelta(days=1)
    return d


def _add_business_days(d: date, n: int) -> date:
    """Return the date `n` business days after `d` (n=0 → d itself)."""
    while n > 0:
        d += timedelta(days=1)
        if d.weekday() < 5:
            n -= 1
    return d


def _prev_business_day(d: date) -> date:
    """The last business day strictly before ``d``."""
    d -= timedelta(days=1)
    while d.weekday() >= 5:
        d -= timedelta(days=1)
    return d


def _past_business_days(end: date, n: int) -> list[date]:
    """The ``n`` business days ending at ``end`` (inclusive), oldest first."""
    days: list[date] = []
    d = end
    while len(days) < n:
        if d.weekday() < 5:
            days.append(d)
        d -= timedelta(days=1)
    days.reverse()
    return days


def _compute_range(days_ahead: int) -> tuple[date, date, list[date]]:
    start = _next_business_day(date.today())
    end = _add_business_days(start, days_ahead - 1)
    exps: list[date] = []
    d = start
    while d <= end:
        if d.weekday() < 5:
            exps.append(d)
        d += timedelta(days=1)
    return start, end, exps


